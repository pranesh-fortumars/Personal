function slugify(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function buildPages(seed: TemplateSeed): PageContent[] {
  const enNames = seed.couple || '';
  const taNames = seed.taCouple || seed.couple || '';
  const enHost = seed.host || '';
  const taHost = seed.taHost || seed.host || '';

  const pages: PageContent[] = [];

  for (const pt of seed.pages) {
    if (pt === 'cover') {
      pages.push({
        type: 'cover',
        en: { title: seed.name, body: seed.message, host: enHost, names: enNames },
        ta: { title: seed.tamilName, body: seed.taMessage, host: taHost, names: taNames },
      });
    } else if (pt === 'invite') {
      pages.push({
        type: 'invite',
        en: {
          title: seed.eventTitle,
          body: seed.message,
          host: enHost,
          names: enNames,
          date: seed.date,
          time: seed.time,
          venue: seed.venue,
        },
        ta: {
          title: seed.taEventTitle,
          body: seed.taMessage,
          host: taHost,
          names: taNames,
          date: seed.date,
          time: seed.time,
          venue: seed.taVenue || seed.venue,
        },
      });
    } else if (pt === 'details') {
      pages.push({
        type: 'details',
        en: {
          title: 'Event Details',
          body: seed.message,
          names: enNames,
          date: seed.date,
          time: seed.time,
          venue: seed.venue,
          address: seed.address,
        },
        ta: {
          title: 'நிகழ்வு விவரம்',
          body: seed.taMessage,
          names: taNames,
          date: seed.date,
          time: seed.time,
          venue: seed.taVenue || seed.venue,
          address: seed.address,
        },
      });
    } else if (pt === 'rsvp') {
      pages.push({
        type: 'rsvp',
        en: {
          title: 'RSVP',
          body: 'We look forward to celebrating with you.',
          rsvp: seed.rsvp,
          venue: seed.venue,
          address: seed.address,
        },
        ta: {
          title: 'வருகை உறுதி',
          body: 'உங்களுடன் கொண்டாட ஆவலுடன் காத்திருக்கிறோம்.',
          rsvp: seed.rsvp,
          venue: seed.taVenue || seed.venue,
          address: seed.address,
        },
      });
    }
  }
  return pages;
}

